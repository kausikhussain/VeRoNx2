// Helper to look up an outfit URL by product ID or essentials filename
export function getOutfitUrlForProduct(productIdOrFile: string): string | null {
  const match = assetManifest.find(
    (item) =>
      item.id === productIdOrFile ||
      item.essentialsFile === productIdOrFile ||
      item.essentialsUrl === productIdOrFile
  );
  return match ? match.outfitUrl : null;
}
